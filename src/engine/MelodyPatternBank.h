// ── Transpose / voicing helpers (pure, key-relative) ──

// Resolve a note's absolute MIDI pitch in a TARGET key. Changes rootPc only;
// degree + octave (the contour + register) are preserved, so the phrase stays
// in scale by construction. Returns -1 if out of range (contract: callers must
// treat -1 as invalid, same as PhraseGenerator::scaleDegreeToPitch).
inline int melodyDegreeToPitch(const MelodicPhrase& p, int targetRootPc, int degree, int octave)
{
    const MelodyScale& s = melodyScales()[p.scaleMode];
    if (degree < 0 || degree >= s.n) return -1;
    const int pitch = 12 * octave + targetRootPc + s.intervals[degree];
    return (pitch >= 0 && pitch <= 127) ? pitch : -1;
}

// Transpose a single stored note into a target key, preserving register by
// choosing the NEAREST transposition direction (delta wrapped to [-5,+6]
// semitones). This is the high-level "play phrase in key K" call: it keeps
// the contour and octave register, so a phrase never jumps an octave when
// the target root wraps mod 12 (e.g. G -> C is +5, not -7).
inline int melodyNotePitch(const MelodicPhrase& p, const MelodyNote& n, int targetRootPc)
{
    const MelodyScale& s = melodyScales()[p.scaleMode];
    if (n.degree < 0 || n.degree >= s.n) return -1;
    const int srcPitch = 12 * n.octave + p.rootPc + s.intervals[n.degree];
    int delta = targetRootPc - p.rootPc;
    while (delta > 6) delta -= 12;
    while (delta < -5) delta += 12;
    const int pitch = srcPitch + delta;
    return (pitch >= 0 && pitch <= 127) ? pitch : -1;
}

// Pointer to a phrase's note array (into the flat melodyNotes() buffer).
inline const MelodyNote* melodyPhraseNotes(const MelodicPhrase& p)
{
    return melodyNotes() + p.noteOffset;
}

// True if a pitch's pitch-class belongs to the given scale+root.
inline bool melodyNoteInScale(int pitch, int targetRootPc, int scaleMode)
{
    const MelodyScale& s = melodyScales()[scaleMode];
    const int pc = ((pitch % 12) + 12) % 12;
    for (int i = 0; i < s.n; ++i)
        if ((((targetRootPc + s.intervals[i]) % 12) + 12) % 12 == pc) return true;
    return false;
}

