def test_build_single_dump_framing_and_checksum():
    base = {i: (i * 3) % 128 for i in range(240)}
    dump = xd.build_single_dump(base, {}, name="P")
    assert len(dump) == 265
    assert dump[0] == 0xF0 and dump[1] == 0x3E and dump[2] == 0x0E
    assert dump[3] == 0x00 and dump[4] == 0x10
    assert dump[5] == 0x00 and dump[6] == 0x00 and dump[264] == 0xF7
    assert dump[263] == xd.compute_checksum(dump)
    assert sum(dump[7:263]) % 128 == dump[263]
    assert dump[247:263] == b"P".ljust(16, b" ")
    for idx in range(240):
        assert dump[7 + idx] == (idx * 3) % 128


def test_build_single_dump_overrides_by_name_and_index_only_intended_differ():
    base = {i: (i * 7) % 128 for i in range(240)}
    dump = xd.build_single_dump(base, {"EffectType": 5, 62: 99}, name="X")
    ref = xd.build_single_dump(base, {}, name="X")
    diffs = [i for i in range(265) if dump[i] != ref[i]]
    assert diffs == [69, 83, 263]           # F1Cutoff@69, EffectType@83
    assert dump[83] == 5 and dump[69] == 99
    assert dump[263] == xd.compute_checksum(dump)


def test_build_single_dump_name_encoding():
    base = {0: 1}
    dump = xd.build_single_dump(base, {}, name="1234567890123456789")
    assert dump[247:263] == b"1234567890123456"
    dump = xd.build_single_dump(base, {}, name="ab")
    assert dump[247:263] == b"ab".ljust(16, b" ")
    with pytest.raises(xd.DumpError):
        xd.build_single_dump(base, {}, name="\u20ac")   # not latin-1


def test_build_single_dump_validation():
    with pytest.raises(xd.DumpError):
        xd.build_single_dump({0: 128}, {})
    with pytest.raises(xd.DumpError):
        xd.build_single_dump({240: 0}, {})          # name bytes are param 240+
    with pytest.raises(xd.DumpError):
        xd.build_single_dump({0: 1}, {"Nope": 3})   # unknown name
    with pytest.raises(xd.DumpError):
        xd.build_single_dump({0: 1}, {"EffectType": 128})
    with pytest.raises(xd.DumpError):
        xd.build_single_dump({0: 1}, {}, device=128)


def test_patch_dump_preserves_header_and_recomputes_checksum():
    base = mk_dump(device=3, bank=0x20, program=9, name="Parent Patch")
    out = xd.patch_dump(base, {"F1Cutoff": 123})
    diffs = [i for i in range(265) if out[i] != base[i]]
    assert diffs == [69, 263]
    assert out[3] == 3 and out[5] == 0x20 and out[6] == 9
    assert out[247:263] == base[247:263]
    assert out[263] == xd.compute_checksum(out)


def test_load_dump_rejects_bad_input(tmp_path):
    good = mk_dump()
    p = tmp_path / "ok.syx"
    p.write_bytes(good)
    assert xd.load_dump(str(p)) == good
    mutators = (lambda d: d[:-1],
                lambda d: b"\xf1" + d[1:],
                lambda d: d[:-1] + b"\x00",
                lambda d: d[:4] + b"\x11" + d[5:])
    for i, mutator in enumerate(mutators):
        bad = tmp_path / ("bad%d.syx" % i)
        bad.write_bytes(mutator(good))
        with pytest.raises(xd.DumpError):
            xd.load_dump(str(bad))


