def mk_dump(name="Original Name", device=0x00, bank=0x00, program=0x07):
    dump = bytearray(xd.DUMP_LEN)
    for idx in range(xd.PARAM_INDEX_LAST + 1):
        dump[xd.IDX_PARAM_FIRST + idx] = (idx * 7) % 128
    dump[xd.IDX_NAME:xd.IDX_NAME + xd.NAME_LEN] = \
        name.encode("latin-1").ljust(xd.NAME_LEN, b" ")
    dump[xd.IDX_F0] = 0xF0
    dump[xd.IDX_ID_WALDORF] = 0x3E
    dump[xd.IDX_ID_MACHINE] = 0x0E
    dump[xd.IDX_DEVICE] = device
    dump[xd.IDX_CMD] = 0x10
    dump[xd.IDX_BANK] = bank
    dump[xd.IDX_PROGRAM] = program
    dump[xd.IDX_END] = 0xF7
    dump[xd.IDX_CHECKSUM] = xd.compute_checksum(dump)
    return bytes(dump)


def _varlen(value):
    out = bytearray([value & 0x7F])
    value >>= 7
    while value:
        out.insert(0, 0x80 | (value & 0x7F))
        value >>= 7
    return bytes(out)


def mk_smf_bank(dumps, extra_multi=True):
    """SMF bytes wrapping the dumps as F0 events (+ one MultiDump decoy)."""
    events = bytearray()
    if extra_multi:
        multi = bytearray(mk_dump())
        multi[xd.IDX_CMD] = 0x11
        multi[xd.IDX_NAME:xd.IDX_NAME + 16] = b"MultiDecoy      "
        multi[xd.IDX_CHECKSUM] = xd.compute_checksum(multi)
        events += b"\x00\xf0" + _varlen(len(multi) - 1) + multi[1:]
    for d in dumps:
        events += b"\x00\xf0" + _varlen(len(d) - 1) + d[1:]
    track = b"MTrk" + len(events).to_bytes(4, "big") + bytes(events)
    header = b"MThd" + (6).to_bytes(4, "big") + (0).to_bytes(2, "big") \
        + (1).to_bytes(2, "big") + (96).to_bytes(2, "big")
    return header + track


