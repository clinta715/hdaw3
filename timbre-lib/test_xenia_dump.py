def test_mapping_fixture_byte_match_all_sidecars():
    if not os.path.isdir(BANK_ROOT):
        pytest.skip("microwave bank corpus not mounted")
    total = 0
    for sc_path in _sidecar_banks():
        bank_path = sc_path[: -len(".xenia.json")]
        with open(sc_path, encoding="utf-8") as fh:
            sc = json.load(fh)
        rows = xd.load_bank(bank_path)
        fmap = {r["name"]: r["dump"] for r in rows}
        container = rows[0]["container"] if rows else None
        for name, kv in sc.get("params", {}).items():
            if name not in fmap:
                continue                      # name-edge cases (see .md)
            dump = fmap[name]
            for k, v in kv.items():
                pos = (7 if container == "usb" else 5) + int(k)
                assert dump[pos] == v, (bank_path, name, k, pos)
                total += 1
    assert total > 1_000_000


def test_corpus_checksum_and_anchor_bytes():
    if not os.path.isdir(BANK_ROOT):
        pytest.skip("microwave bank corpus not mounted")
    dumps = checksum_ok = version1 = 0
    for sc_path in _sidecar_banks():
        bank_path = sc_path[: -len(".xenia.json")]
        if os.path.splitext(bank_path)[1].lower() in (".usb", "\u00b5sb"):
            continue                          # framing synthesized, not real
        for row in xd.load_bank(bank_path):
            dump = row["dump"]
            dumps += 1
            assert dump[0] == 0xF0 and dump[264] == 0xF7
            assert (dump[1], dump[2], dump[4]) == (0x3E, 0x0E, 0x10)
            if xd.compute_checksum(dump) == dump[263]:
                checksum_ok += 1
            if dump[7] == 1:
                version1 += 1
    assert dumps > 3000
    assert checksum_ok == dumps               # formula holds for every dump
    assert version1 >= dumps - 4              # Version param (index 0) == 1


def _refind_parent_dump(resolution, preset):
    """Re-find the byte-verified parent dump named in baseResolution."""
    named = xd._named_values(preset, xd.name_to_offset())
    shift = -2 if resolution["how"] == "vocab-shifted" else 0
    for path in xd._bank_files(BANK_ROOT):
        if os.path.basename(path) != resolution["bank"]:
            continue
        for row in xd.load_bank(path):
            if row["name"] != resolution["patch"]:
                continue
            if row["container"] != resolution["container"]:
                continue
            if xd._matches(row["dump"], named, shift) == len(named):
                return row["dump"]
    raise AssertionError("baseResolution dump not re-findable: %r"
                         % (resolution,))


def test_injectable_morphs_deliverable():
    if not os.path.isdir(BANK_ROOT):
        pytest.skip("microwave bank corpus not mounted")
    with open(os.path.join(REPO, MORPHS_OUT_REL), encoding="utf-8") as fh:
        text = fh.read()
    doc = json.loads(text)
    assert doc["schema"] == "hdaw.matrix.preset.morph.v1"
    assert doc["sourceSheet"] == SHEET_REL.replace(os.sep, "/")
    assert doc["derivedFrom"] == MORPHS_IN_REL.replace(os.sep, "/")
    assert doc["sysexRoots"] == ["microwave"]
    assert doc["unverified"] is True
    for marker in ("/mnt/", "D:/pdf", ":/pdf"):
        assert marker not in text
    with open(os.path.join(REPO, MORPHS_IN_REL), encoding="utf-8") as fh:
        morphs = json.load(fh)
    with open(os.path.join(REPO, SHEET_REL), encoding="utf-8") as fh:
        sheet = json.load(fh)
    by_id = {p["id"]: p for p in sheet["presets"]}
    assert [p["pair"] for p in doc["pairs"]] == \
        [p["pair"] for p in morphs["pairs"]]
    name_to_off = xd.name_to_offset()
    for pair in doc["pairs"]:
        res = pair["baseResolution"]
        assert res["how"] in ("verified", "vocab-shifted")
        # per-pair provenance (off-by-2 fix): .usb parents resolve under the
        # direct labeling, .mid parents under the corrected shifted-back
        # labeling -- both byte-verify at dump offset 7+index
        assert res["provenance"] == ("verified"
                                     if res["container"] == "usb"
                                     else "mid-corrected")
        assert res["byteMatches"] >= xd.MIN_PARENT_CHECKS
        parent = by_id[pair["parents"][0]["id"]]
        base = _refind_parent_dump(res, parent)
        shift = -2 if res["how"] == "vocab-shifted" else 0
        assert len(pair["steps"]) == 4
        for step in pair["steps"]:
            sysex = step["sysex"]
            assert len(sysex) == 265
            assert sysex[0] == 0xF0 and sysex[264] == 0xF7
            assert (sysex[1], sysex[2], sysex[4]) == (0x3E, 0x0E, 0x10)
            assert sysex[5] == 0x20     # single edit buffer (live-verified)
            assert sysex[263] == xd.compute_checksum(sysex)
            # independent re-derivation: parent bytes + mapped step values
            expected = bytearray(base)
            expected[5] = 0x20          # delivery bank byte (outside cksum)
            touched = {5}
            for name, value in sorted(step["preset"]["params"].items()):
                if value is None or name not in name_to_off:
                    continue
                pos = name_to_off[name] + shift
                expected[pos] = int(round(value)) \
                    if isinstance(value, float) else value
                touched.add(pos)
            expected[263] = xd.compute_checksum(expected)
            diff_ix = [i for i in range(265) if list(expected)[i] != sysex[i]][:8]
            assert list(expected) == sysex, (pair['pair'], step['step'], diff_ix)
            assert touched - {5}                    # at least one param write
            for i in range(265):                    # nothing else moved
                if i not in touched and i != 263:
                    assert sysex[i] == base[i]


def test_injectable_morphs_rebuild_byte_stable():
    if not os.path.isdir(BANK_ROOT):
        pytest.skip("microwave bank corpus not mounted")
    doc = xd.build_injectable_morphs(
        os.path.join(REPO, MORPHS_IN_REL), BANK_ROOT)
    # the committed deliverable carries the two documented post-processing
    # steps of the off-by-2 regeneration (xenia-offset-map.md, "Morph
    # injectability"): every step's SysEx is stamped with the single-edit-
    # buffer bank byte 0x20 (byte 5, outside the checksum range; verified
    # audible live 2026-09-16), and each pair records per-parent provenance
    # ("verified" for .usb banks, "mid-corrected" for .mid banks).
    for pair in doc["pairs"]:
        pair["baseResolution"]["provenance"] = (
            "verified" if pair["baseResolution"]["container"] == "usb"
            else "mid-corrected")
        for step in pair["steps"]:
            sysex = list(step["sysex"])
            sysex[5] = 0x20
            step["sysex"] = sysex
    with open(os.path.join(REPO, MORPHS_OUT_REL), "rb") as fh:
        assert fh.read() == render_json(doc).encode("utf-8")


