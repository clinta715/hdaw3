def _sidecar_banks():
    out = []
    for dirpath, dirnames, filenames in os.walk(BANK_ROOT):
        dirnames.sort()
        for fn in sorted(filenames):
            if fn.endswith(".xenia.json"):
                out.append(os.path.join(dirpath, fn))
    return sorted(out)


