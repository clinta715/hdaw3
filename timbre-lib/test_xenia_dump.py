def test_cli_round_trip_and_errors(tmp_path):
    d1 = mk_dump(name="Cli Base", bank=1)
    bank = tmp_path / "b.mid"
    bank.write_bytes(mk_smf_bank([d1]))
    out = tmp_path / "out.syx"
    proc = _run_cli(["--base-bank", str(bank), "--patch", "Cli Base",
                     "--set", "EffectType=5,F1Cutoff=90", "--name", "Cli New",
                     "--bank", "1", "--out", str(out)])
    assert proc.returncode == 0, proc.stderr
    expected = xd.build_single_dump(
        {i: d1[7 + i] for i in range(240)},
        {"EffectType": 5, "F1Cutoff": 90}, name="Cli New", bank=1)
    assert out.read_bytes() == expected
    proc = _run_cli(["--base-bank", str(bank), "--patch", "Nope",
                     "--out", str(out)])
    assert proc.returncode == 2 and "not found" in proc.stderr
    proc = _run_cli(["--base-bank", str(bank), "--patch", "Cli Base",
                     "--set", "EffectType=x", "--out", str(out)])
    assert proc.returncode == 2
    proc = _run_cli(["--base-bank", str(bank)])
    assert proc.returncode == 2


